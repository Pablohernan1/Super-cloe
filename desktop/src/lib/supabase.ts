import { createClient } from '@supabase/supabase-js'

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL
const supabaseAnonKey = import.meta.env.VITE_SUPABASE_ANON_KEY

if (!supabaseUrl || !supabaseAnonKey) {
  throw new Error('Faltan VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY (.env en desktop/)')
}

// Sesión persistida en localStorage del propio proceso de Electron -- no hay
// cookies/servidor Next.js de por medio, la app habla directo con Supabase
// (decisión de arquitectura: ver .claude/skills/cloe-financiacion/SKILL.md).
export const supabase = createClient(supabaseUrl, supabaseAnonKey, {
  auth: {
    persistSession: true,
    autoRefreshToken: true,
    detectSessionInUrl: false,
  },
})
